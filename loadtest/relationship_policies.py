"""Load test for policies derived with ``Policy.from_relationship``.

Compares the policy SQL generated by ``from_relationship`` with alternative
ways of writing the same access rule, on the same data, to see what the
generated ``EXISTS`` subqueries cost and whether ``STABLE SECURITY DEFINER``
helper functions are worth it.

Schema (``account`` is the context value ``rls.account_id``)::

    authors  (account_id)          owner policy: account_id = <context>
    books    -> authors            many-to-one
    chapters -> books -> authors   many-to-one chain
    tags     (account_id)          owner policy
    article_tags (article_id, tag_id)
    articles <-> tags              many-to-many through article_tags

``authors``, ``tags`` and ``article_tags`` always use the same policies.
The policies of ``books``, ``chapters`` and ``articles`` are swapped between
these variants:

``none``
    ``USING (true)``: RLS is applied but does not filter (baseline).
``denormalized``
    ``account_id = <context>`` on a denormalized column (no subquery; not
    available for many-to-many).
``generated``
    What ``Policy.from_relationship`` generates: a correlated ``EXISTS``
    that reads the related table under its own policies.
``in_subquery``
    ``fk IN (SELECT id FROM related)``: same semantics as ``generated``
    (the related table's policies still apply), but uncorrelated, so
    Postgres can evaluate it once per query as a hashed subplan.
``definer_per_row``
    ``rls_<x>_visible(fk)``: a ``STABLE SECURITY DEFINER`` function that
    checks one row, called per row.  It bypasses the related table's RLS
    and re-implements its rule.
``definer_array``
    ``fk = ANY ((SELECT rls_accessible_<x>_ids()))``: a ``STABLE SECURITY
    DEFINER`` function returning the accessible ids, evaluated once per
    query as an InitPlan.

Every variant keeps the ``OR <bypass_rls>`` clause that generated policies
have.  Results of each query are compared between variants, so a variant
that does not implement the same rule is reported.

Times are the server's execution time from ``EXPLAIN (ANALYZE, TIMING
OFF)``, so client overhead is excluded.  Run with::

    python -m loadtest.relationship_policies --scale 1 --repeats 5

It starts a throwaway Postgres with ``testing.postgresql`` unless
``--url`` is given (the database must be empty and the user a superuser).
"""

