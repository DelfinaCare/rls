"""Load test for policies derived with ``Policy.from_relationship``.

Compares the policy SQL generated by ``from_relationship`` with alternative
ways of writing the same access rule, on the same data, to see what the
generated ``EXISTS`` subqueries cost and whether ``STABLE SECURITY DEFINER``
helper functions are worth it.

Schema (``account`` is the context value ``rls.account_id``)::

    authors  (account_id)          owner policy: account_id = <context>
    books    -> authors            many-to-one
    chapters -> books -> authors   many-to-one chain
    tags     (account_id)          owner policy
    article_tags (article_id, tag_id)
    articles <-> tags              many-to-many through article_tags

``authors``, ``tags`` and ``article_tags`` always use the same policies.
The policies of ``books``, ``chapters`` and ``articles`` are swapped between
these variants:

``none``
    ``USING (true)``: RLS is applied but does not filter (baseline).
``denormalized``
    ``account_id = <context>`` on a denormalized column (no subquery; not
    available for many-to-many).
``generated``
    What ``Policy.from_relationship`` generates: a correlated ``EXISTS``
    that reads the related table under its own policies.
``in_subquery``
    ``fk IN (SELECT id FROM related)``: same semantics as ``generated``
    (the related table's policies still apply), but uncorrelated, so
    Postgres can evaluate it once per query as a hashed subplan.
``definer_per_row``
    ``rls_<x>_visible(fk)``: a ``STABLE SECURITY DEFINER`` function that
    checks one row, called per row.  It bypasses the related table's RLS
    and re-implements its rule.
``definer_array``
    ``fk = ANY ((SELECT rls_accessible_<x>_ids()))``: a ``STABLE SECURITY
    DEFINER`` function returning the accessible ids, evaluated once per
    query as an InitPlan.

Every variant keeps the ``OR <bypass_rls>`` clause that generated policies
have.  Results of each query are compared between variants, so a variant
that does not implement the same rule is reported.

Times are the server's execution time from ``EXPLAIN (ANALYZE, TIMING
OFF)``, so client overhead is excluded.  Run with::

    python -m loadtest.relationship_policies --scale 1 --repeats 5

It starts a throwaway Postgres with ``testing.postgresql`` unless
``--url`` is given (the database must be empty and the user a superuser).
"""

import argparse
import contextlib
import dataclasses
import hashlib
import json
import statistics
import sys
import time
import typing
from collections import abc

import sqlalchemy
from sqlalchemy import orm
from sqlalchemy import sql

from rls import create_policies
from rls import policy
from rls import register

ROLE = "loadtest_user"
CTX = "CAST(nullif(current_setting('rls.account_id', true), '') AS INTEGER)"
BYPASS = "CAST(nullif(current_setting('rls.bypass_rls', true), '') AS BOOLEAN) = true"
ACCOUNT_ID = policy.ConditionArg(comparator_name="account_id", type=sqlalchemy.Integer)
VARIANTS = (
    "none",
    "denormalized",
    "generated",
    "in_subquery",
    "definer_per_row",
    "definer_array",
)
BENCH_TABLES = ("books", "chapters", "articles")


def _owner_policy() -> policy.Policy:
    return policy.Policy.from_sqla(
        expr=lambda x: sql.column("account_id") == x,
        condition_args=[ACCOUNT_ID],
        cmd=policy.Command.all,
    )


class Base(orm.DeclarativeBase):
    pass


register.base_wrapper(Base)

article_tags = sqlalchemy.Table(
    "article_tags",
    Base.metadata,
    sqlalchemy.Column(
        "article_id", sqlalchemy.ForeignKey("articles.id"), primary_key=True
    ),
    sqlalchemy.Column(
        "tag_id", sqlalchemy.ForeignKey("tags.id"), primary_key=True, index=True
    ),
)


class Author(Base):
    __tablename__ = "authors"
    id: orm.Mapped[int] = orm.mapped_column(primary_key=True)
    account_id: orm.Mapped[int] = orm.mapped_column(index=True)
    __rls_policies__: typing.ClassVar = [_owner_policy()]


class Book(Base):
    __tablename__ = "books"
    id: orm.Mapped[int] = orm.mapped_column(primary_key=True)
    author_id: orm.Mapped[int] = orm.mapped_column(
        sqlalchemy.ForeignKey("authors.id"), index=True
    )
    account_id: orm.Mapped[int] = orm.mapped_column(index=True)
    title: orm.Mapped[str]
    author: orm.Mapped[Author] = orm.relationship()
    __rls_policies__: typing.ClassVar = [policy.Policy.from_relationship("author")]


class Chapter(Base):
    __tablename__ = "chapters"
    id: orm.Mapped[int] = orm.mapped_column(primary_key=True)
    book_id: orm.Mapped[int] = orm.mapped_column(
        sqlalchemy.ForeignKey("books.id"), index=True
    )
    account_id: orm.Mapped[int] = orm.mapped_column(index=True)
    title: orm.Mapped[str]
    book: orm.Mapped[Book] = orm.relationship()
    __rls_policies__: typing.ClassVar = [policy.Policy.from_relationship("book")]


class Tag(Base):
    __tablename__ = "tags"
    id: orm.Mapped[int] = orm.mapped_column(primary_key=True)
    account_id: orm.Mapped[int] = orm.mapped_column(index=True)
    __rls_policies__: typing.ClassVar = [_owner_policy()]


class Article(Base):
    __tablename__ = "articles"
    id: orm.Mapped[int] = orm.mapped_column(primary_key=True)
    title: orm.Mapped[str]
    tags: orm.Mapped[list[Tag]] = orm.relationship(secondary=article_tags)
    __rls_policies__: typing.ClassVar = [policy.Policy.from_relationship("tags")]


register.table_policies(
    article_tags,
    [
        policy.Policy.from_sqla(
            expr=lambda: sqlalchemy.exists().where(Tag.id == sql.column("tag_id")),
            condition_args=[],
            cmd=policy.Command.select,
        )
    ],
)

# Helper functions of the SECURITY DEFINER variants.  They are owned by the
# (superuser) admin, so they read the tables without RLS and re-implement
# the rules of authors and tags.
FUNCTIONS = f"""
CREATE FUNCTION rls_author_visible(author_id integer) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT EXISTS (SELECT 1 FROM authors
                   WHERE id = $1 AND account_id = {CTX})
$$;
CREATE FUNCTION rls_book_visible(book_id integer) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT EXISTS (SELECT 1 FROM books JOIN authors ON authors.id = books.author_id
                   WHERE books.id = $1 AND authors.account_id = {CTX})
$$;
CREATE FUNCTION rls_article_visible(article_id integer) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT EXISTS (SELECT 1 FROM article_tags JOIN tags ON tags.id = article_tags.tag_id
                   WHERE article_tags.article_id = $1
                   AND tags.account_id = {CTX})
$$;
CREATE FUNCTION rls_accessible_author_ids() RETURNS integer[]
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT coalesce(array_agg(id), '{{}}') FROM authors WHERE account_id = {CTX}
$$;
CREATE FUNCTION rls_accessible_book_ids() RETURNS integer[]
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT coalesce(array_agg(books.id), '{{}}')
    FROM books JOIN authors ON authors.id = books.author_id
    WHERE authors.account_id = {CTX}
$$;
CREATE FUNCTION rls_accessible_article_ids() RETURNS integer[]
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT coalesce(array_agg(DISTINCT article_tags.article_id), '{{}}')
    FROM article_tags JOIN tags ON tags.id = article_tags.tag_id
    WHERE tags.account_id = {CTX}
$$;
"""


def _variant_exprs() -> dict[str, dict[str, str | None]]:
    """The USING expression of each benchmarked table, per variant."""
    resolved = policy.resolved_policies(Base.metadata)

    def generated(table: str) -> str:
        (p,) = resolved[table]
        return typing.cast(policy.Policy, p).expr

    articles_in = (
        "id IN (SELECT article_tags.article_id FROM article_tags "
        "JOIN tags ON tags.id = article_tags.tag_id)"
    )
    exprs: dict[str, dict[str, str | None]] = {
        "none": dict.fromkeys(BENCH_TABLES, "true"),
        "denormalized": {
            "books": f"account_id = {CTX}",
            "chapters": f"account_id = {CTX}",
            "articles": None,
        },
        "generated": {table: generated(table) for table in BENCH_TABLES},
        "in_subquery": {
            "books": "author_id IN (SELECT id FROM authors)",
            "chapters": "book_id IN (SELECT id FROM books)",
            "articles": articles_in,
        },
        "definer_per_row": {
            "books": "rls_author_visible(author_id)",
            "chapters": "rls_book_visible(book_id)",
            "articles": "rls_article_visible(id)",
        },
        "definer_array": {
            "books": "author_id = ANY ((SELECT rls_accessible_author_ids())::integer[])",
            "chapters": "book_id = ANY ((SELECT rls_accessible_book_ids())::integer[])",
            "articles": "id = ANY ((SELECT rls_accessible_article_ids())::integer[])",
        },
    }
    for variant, tables in exprs.items():
        for table, expr in tables.items():
            # Generated policies already contain the bypass clause.
            if expr is not None and variant != "generated":
                tables[table] = f"{expr} OR {BYPASS}"
    return exprs


@dataclasses.dataclass(frozen=True)
class Sizes:
    accounts: int
    authors: int
    books: int
    chapters: int
    tags: int
    articles: int

    @classmethod
    def scaled(cls, scale: float, accounts: int) -> "Sizes":
        def n(base: int) -> int:
            return max(1, int(base * scale))

        return cls(
            accounts=accounts,
            authors=n(20_000),
            books=n(200_000),
            chapters=n(1_000_000),
            tags=n(20_000),
            articles=n(200_000),
        )


def _load(connection: sqlalchemy.Connection, sizes: Sizes) -> None:
    """Fill the tables, as the admin (RLS does not apply to superusers)."""
    statements = [
        "SELECT setseed(0.42)",
        f"""INSERT INTO authors (id, account_id)
            SELECT i, 1 + floor(random() * {sizes.accounts})::int
            FROM generate_series(1, {sizes.authors}) i""",
        f"""INSERT INTO books (id, author_id, account_id, title)
            SELECT s.i, a.id, a.account_id, 'book ' || s.i
            FROM (SELECT i, 1 + floor(random() * {sizes.authors})::int AS parent
                  FROM generate_series(1, {sizes.books}) i) s
            JOIN authors a ON a.id = s.parent""",
        f"""INSERT INTO chapters (id, book_id, account_id, title)
            SELECT s.i, b.id, b.account_id, 'chapter ' || s.i
            FROM (SELECT i, 1 + floor(random() * {sizes.books})::int AS parent
                  FROM generate_series(1, {sizes.chapters}) i) s
            JOIN books b ON b.id = s.parent""",
        f"""INSERT INTO tags (id, account_id)
            SELECT i, 1 + floor(random() * {sizes.accounts})::int
            FROM generate_series(1, {sizes.tags}) i""",
        f"""INSERT INTO articles (id, title)
            SELECT i, 'article ' || i FROM generate_series(1, {sizes.articles}) i""",
        # Two tags per article.
        f"""INSERT INTO article_tags (article_id, tag_id)
            SELECT i, t FROM generate_series(1, {sizes.articles}) i,
            LATERAL (SELECT 1 + floor(random() * {sizes.tags})::int AS t1) r,
            LATERAL (VALUES (r.t1), (1 + r.t1 % {sizes.tags})) v(t)
            ON CONFLICT DO NOTHING""",
    ]
    for statement in statements:
        connection.execute(sqlalchemy.text(statement))


def _set_variant(connection: sqlalchemy.Connection, variant: str) -> bool:
    """Replace the policies of the benchmarked tables.  Returns False if the
    variant does not apply to every table."""
    exprs = _variant_exprs()[variant]
    for table in BENCH_TABLES:
        names: list[str] = list(
            connection.execute(
                sqlalchemy.text(
                    "SELECT policyname FROM pg_policies WHERE tablename = :t"
                ),
                {"t": table},
            ).scalars()
        )
        for name in names:
            connection.execute(sqlalchemy.text(f'DROP POLICY "{name}" ON {table}'))
        expr = exprs[table]
        # Without a policy, forced RLS denies everything.
        connection.execute(
            sqlalchemy.text(
                f"CREATE POLICY bench ON {table} FOR ALL USING ({expr or 'false'})"
            )
        )
    return all(expr is not None for expr in exprs.values())


@dataclasses.dataclass(frozen=True)
class Query:
    table: str
    name: str
    sql: str  # formatted with the account's parameters


QUERIES = (
    Query("books", "count", "SELECT count(*) FROM books"),
    Query("books", "point", "SELECT * FROM books WHERE id = {book_id}"),
    Query("books", "by_fk", "SELECT * FROM books WHERE author_id = {author_id}"),
    Query("books", "page", "SELECT * FROM books ORDER BY id LIMIT 50"),
    Query("chapters", "count", "SELECT count(*) FROM chapters"),
    Query("chapters", "point", "SELECT * FROM chapters WHERE id = {chapter_id}"),
    Query("chapters", "by_fk", "SELECT * FROM chapters WHERE book_id = {book_id}"),
    Query("chapters", "page", "SELECT * FROM chapters ORDER BY id LIMIT 50"),
    Query("articles", "count", "SELECT count(*) FROM articles"),
    Query("articles", "point", "SELECT * FROM articles WHERE id = {article_id}"),
    Query(
        "articles",
        "by_fk",
        "SELECT articles.* FROM articles JOIN article_tags "
        "ON article_tags.article_id = articles.id "
        "WHERE article_tags.tag_id = {tag_id} ORDER BY articles.id",
    ),
    Query("articles", "page", "SELECT * FROM articles ORDER BY id LIMIT 50"),
)


def _account_params(
    connection: sqlalchemy.Connection, accounts: abc.Iterable[int]
) -> dict[int, dict[str, int]]:
    """Ids of rows each account can see, for the point and by_fk queries."""
    params = {}
    for account in accounts:
        row = connection.execute(
            sqlalchemy.text(
                """SELECT
                (SELECT min(id) FROM authors WHERE account_id = :a),
                (SELECT min(id) FROM books WHERE account_id = :a),
                (SELECT min(id) FROM chapters WHERE account_id = :a),
                (SELECT min(id) FROM tags WHERE account_id = :a),
                (SELECT min(article_id) FROM article_tags
                 JOIN tags ON tags.id = article_tags.tag_id
                 WHERE tags.account_id = :a)"""
            ),
            {"a": account},
        ).one()
        params[account] = dict(
            zip(
                ("author_id", "book_id", "chapter_id", "tag_id", "article_id"),
                (value or 0 for value in row),
                strict=True,
            )
        )
    return params


@dataclasses.dataclass
class Result:
    exec_ms: list[float] = dataclasses.field(default_factory=list)
    plan_ms: list[float] = dataclasses.field(default_factory=list)
    fingerprints: dict[int, str] = dataclasses.field(default_factory=dict)


def _run(
    connection: sqlalchemy.Connection,
    query: Query,
    params: dict[int, dict[str, int]],
    repeats: int,
) -> Result:
    result = Result()
    for account, values in params.items():
        connection.execute(
            sqlalchemy.text("SELECT set_config('rls.account_id', :a, false)"),
            {"a": str(account)},
        )
        statement = query.sql.format(**values)
        rows = connection.execute(sqlalchemy.text(statement)).all()
        result.fingerprints[account] = hashlib.sha256(
            repr(sorted(map(tuple, rows))).encode()
        ).hexdigest()
        for _ in range(repeats):
            plan: dict[str, typing.Any]
            (plan,) = connection.execute(
                sqlalchemy.text(
                    f"EXPLAIN (ANALYZE, TIMING OFF, FORMAT JSON) {statement}"
                )
            ).scalar_one()
            result.exec_ms.append(plan["Execution Time"])
            result.plan_ms.append(plan["Planning Time"])
    return result


def _p95(values: list[float]) -> float:
    return sorted(values)[max(0, round(0.95 * len(values)) - 1)]


@contextlib.contextmanager
def _database(url: str | None) -> abc.Iterator[sqlalchemy.engine.URL]:
    if url is not None:
        yield sqlalchemy.engine.make_url(url)
        return
    import testing.postgresql

    postgresql = testing.postgresql.Postgresql(
        postgres_args="-h 127.0.0.1 -F -c logging_collector=off"
    )
    try:
        yield sqlalchemy.engine.make_url(postgresql.url()).set(
            drivername="postgresql+psycopg"
        )
    finally:
        postgresql.stop()


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--scale", type=float, default=1.0)
    parser.add_argument("--accounts", type=int, default=1_000)
    parser.add_argument(
        "--sample-accounts",
        type=int,
        default=3,
        help="accounts each query is run as",
    )
    parser.add_argument("--repeats", type=int, default=3)
    parser.add_argument("--variants", nargs="+", default=list(VARIANTS))
    parser.add_argument(
        "--explain",
        metavar="TABLE.QUERY",
        help="print the plan of one query for each variant and exit",
    )
    parser.add_argument("--url", help="use this (empty) database")
    args = parser.parse_args(argv)
    sizes = Sizes.scaled(args.scale, args.accounts)

    with _database(args.url) as url:
        admin = sqlalchemy.create_engine(url)
        started = time.monotonic()
        with admin.begin() as connection:
            Base.metadata.create_all(connection)
            create_policies.create_policies_no_commit(Base, connection)
            connection.execute(sqlalchemy.text(FUNCTIONS))
            _load(connection, sizes)
            connection.execute(
                sqlalchemy.text(
                    f"CREATE ROLE {ROLE} LOGIN PASSWORD '{ROLE}';"
                    f"GRANT SELECT ON ALL TABLES IN SCHEMA public TO {ROLE};"
                )
            )
        with admin.connect().execution_options(
            isolation_level="AUTOCOMMIT"
        ) as connection:
            connection.execute(sqlalchemy.text("VACUUM ANALYZE"))
            accounts = list(range(1, args.sample_accounts + 1))
            params = _account_params(connection, accounts)
        print(
            f"Loaded {sizes} in {time.monotonic() - started:.1f}s",
            file=sys.stderr,
        )
        user = sqlalchemy.create_engine(url.set(username=ROLE, password=ROLE))

        if args.explain:
            table, name = args.explain.split(".")
            (query,) = [q for q in QUERIES if (q.table, q.name) == (table, name)]
            for variant in args.variants:
                with admin.begin() as connection:
                    _set_variant(connection, variant)
                with user.connect() as connection:
                    connection.execute(
                        sqlalchemy.text(
                            "SELECT set_config('rls.account_id', :a, false)"
                        ),
                        {"a": str(accounts[0])},
                    )
                    statement = query.sql.format(**params[accounts[0]])
                    lines: list[str] = list(
                        connection.execute(
                            sqlalchemy.text(f"EXPLAIN (ANALYZE, BUFFERS) {statement}")
                        ).scalars()
                    )
                    print(f"\n### {variant}\n")
                    print("\n".join(lines))
            return

        results: dict[tuple[str, str], dict[str, Result]] = {}
        for variant in args.variants:
            with admin.begin() as connection:
                complete = _set_variant(connection, variant)
            with user.connect() as connection:
                for query in QUERIES:
                    if not complete and _variant_exprs()[variant][query.table] is None:
                        continue
                    print(f"{variant:16} {query.table}.{query.name}", file=sys.stderr)
                    results.setdefault((query.table, query.name), {})[variant] = _run(
                        connection, query, params, args.repeats
                    )

        _report(results, args.variants, sizes)


def _report(
    results: dict[tuple[str, str], dict[str, Result]],
    variants: list[str],
    sizes: Sizes,
) -> None:
    print(f"\nSizes: {json.dumps(dataclasses.asdict(sizes))}\n")
    print("Median execution time in ms (p95 in parentheses).\n")
    print("| query | " + " | ".join(variants) + " |")
    print("|---|" + "---|" * len(variants))
    mismatches = []
    for (table, name), by_variant in results.items():
        reference = by_variant.get("generated")
        cells = []
        for variant in variants:
            result = by_variant.get(variant)
            if result is None:
                cells.append("n/a")
                continue
            cell = (
                f"{statistics.median(result.exec_ms):.2f} ({_p95(result.exec_ms):.2f})"
            )
            if (
                variant != "none"
                and reference is not None
                and result.fingerprints != reference.fingerprints
            ):
                cell += " ≠"
                mismatches.append(f"{table}.{name} ({variant})")
            cells.append(cell)
        print(f"| {table}.{name} | " + " | ".join(cells) + " |")
    if mismatches:
        print(
            "\n≠: results differ from the generated policy's: " + ", ".join(mismatches)
        )


if __name__ == "__main__":
    main()
